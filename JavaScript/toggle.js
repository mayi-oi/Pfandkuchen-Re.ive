function Setup_bilder() {
    const el = document.querySelector('.Setup-overlay')
    if (el) el.classList.toggle('open')
}

function Menutoggle() {
    const el = document.querySelector('.Hauptmenu-content')
    if (el) el.classList.toggle('open')
}

function Musiktoggle() {
    const el = document.querySelector('.Musikplayer-topbar')
    if (el) el.classList.toggle('open')
}

function Musikmenu_toggle() {
    const el = document.querySelector('.Musikplayer-menü')
    if (el) el.classList.toggle('open')
}